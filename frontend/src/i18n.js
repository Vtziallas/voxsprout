export function t(lang, key, ...args) {
  const section = UI[lang] ?? UI.en;
  const v = section[key] ?? UI.en[key];
  return typeof v === 'function' ? v(...args) : (v ?? key);
}

export function disorder(lang, key) {
  return (DISORDERS[lang] ?? DISORDERS.en)[key] ?? (DISORDERS.en[key] ?? key);
}
